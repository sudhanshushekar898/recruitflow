package dev.recruitflow.job.domain;

import dev.recruitflow.shared.persistence.BaseEntity;
import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Objects;
import java.util.Set;
import java.util.UUID;
import org.hibernate.annotations.BatchSize;

@Entity
@Table(name = "jobs")
public class Job extends BaseEntity {

    @Column(nullable = false)
    private UUID clientId;

    @Column(nullable = false, length = 150)
    private String title;

    @Column(columnDefinition = "text")
    private String description;

    @Column(length = 150)
    private String location;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private EmploymentType employmentType;

    private BigDecimal salaryMin;

    private BigDecimal salaryMax;

    @Column(length = 3)
    private String currency;

    @Column(nullable = false)
    private int openings = 1;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private JobStatus status = JobStatus.DRAFT;

    @Column(nullable = false)
    private UUID ownerId;

    private Instant openedAt;

    private Instant closedAt;

    /** Generated by the database from title and location; read-only here. */
    @Column(insertable = false, updatable = false)
    private String searchText;

    @ElementCollection(fetch = FetchType.LAZY)
    @CollectionTable(name = "job_skills", joinColumns = @JoinColumn(name = "job_id"))
    @BatchSize(size = 50)
    private Set<JobSkillEntry> skills = new HashSet<>();

    protected Job() {}

    public Job(UUID clientId, String title, String description, String location, EmploymentType employmentType,
               BigDecimal salaryMin, BigDecimal salaryMax, String currency, int openings, UUID ownerId) {
        this.clientId = clientId;
        this.title = title.trim();
        this.description = clean(description);
        this.location = clean(location);
        this.employmentType = employmentType;
        this.salaryMin = salaryMin;
        this.salaryMax = salaryMax;
        this.currency = currency;
        this.openings = openings;
        this.ownerId = ownerId;
    }

    private static String clean(String v) {
        return v == null || v.isBlank() ? null : v.trim();
    }

    /** Partial update; returns the names of fields that changed (for the audit log). Null leaves a field as is. */
    public List<String> apply(String title, String description, String location, EmploymentType type,
                              BigDecimal salaryMin, BigDecimal salaryMax, String currency, Integer openings, UUID clientId) {
        List<String> changed = new ArrayList<>();
        if (title != null && !title.trim().equals(this.title)) {
            this.title = title.trim();
            changed.add("title");
        }
        if (description != null && !Objects.equals(clean(description), this.description)) {
            this.description = clean(description);
            changed.add("description");
        }
        if (location != null && !Objects.equals(clean(location), this.location)) {
            this.location = clean(location);
            changed.add("location");
        }
        if (type != null && type != employmentType) {
            this.employmentType = type;
            changed.add("employmentType");
        }
        if (salaryMin != null && salaryMin.compareTo(Objects.requireNonNullElse(this.salaryMin, BigDecimal.valueOf(-1))) != 0) {
            this.salaryMin = salaryMin;
            changed.add("salaryMin");
        }
        if (salaryMax != null && salaryMax.compareTo(Objects.requireNonNullElse(this.salaryMax, BigDecimal.valueOf(-1))) != 0) {
            this.salaryMax = salaryMax;
            changed.add("salaryMax");
        }
        if (currency != null && !currency.equals(this.currency)) {
            this.currency = currency;
            changed.add("currency");
        }
        if (openings != null && openings != this.openings) {
            this.openings = openings;
            changed.add("openings");
        }
        if (clientId != null && !clientId.equals(this.clientId)) {
            this.clientId = clientId;
            changed.add("clientId");
        }
        return changed;
    }

    public void replaceSkills(Set<JobSkillEntry> newSkills) {
        skills.clear();
        skills.addAll(newSkills);
    }

    public void moveTo(JobStatus target, Instant now) {
        if (target == JobStatus.OPEN && openedAt == null) {
            openedAt = now;
        }
        closedAt = target == JobStatus.CLOSED ? now : null;
        status = target;
    }

    public UUID getClientId() {
        return clientId;
    }

    public String getTitle() {
        return title;
    }

    public String getDescription() {
        return description;
    }

    public String getLocation() {
        return location;
    }

    public EmploymentType getEmploymentType() {
        return employmentType;
    }

    public BigDecimal getSalaryMin() {
        return salaryMin;
    }

    public BigDecimal getSalaryMax() {
        return salaryMax;
    }

    public String getCurrency() {
        return currency;
    }

    public int getOpenings() {
        return openings;
    }

    public JobStatus getStatus() {
        return status;
    }

    public UUID getOwnerId() {
        return ownerId;
    }

    public Instant getOpenedAt() {
        return openedAt;
    }

    public Instant getClosedAt() {
        return closedAt;
    }

    public Set<JobSkillEntry> getSkills() {
        return Set.copyOf(skills);
    }
}
