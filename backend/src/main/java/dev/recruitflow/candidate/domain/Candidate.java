package dev.recruitflow.candidate.domain;

import dev.recruitflow.shared.persistence.BaseEntity;
import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Objects;
import java.util.Set;
import java.util.UUID;
import org.hibernate.annotations.BatchSize;

@Entity
@Table(name = "candidates")
public class Candidate extends BaseEntity {

    @Column(nullable = false, length = 100)
    private String firstName;

    @Column(nullable = false, length = 100)
    private String lastName;

    /** Stored lower-case. */
    @Column(nullable = false, length = 254)
    private String email;

    @Column(length = 30)
    private String phone;

    @Column(length = 150)
    private String currentTitle;

    @Column(length = 150)
    private String currentCompany;

    @Column(length = 150)
    private String location;

    private Integer yearsExperience;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private CandidateSource source;

    @Column(columnDefinition = "text")
    private String summary;

    @Column(length = 300)
    private String linkedinUrl;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private CandidateStatus status = CandidateStatus.ACTIVE;

    @Column(nullable = false)
    private UUID ownerId;

    @Column(nullable = false)
    private Instant retentionUntil;

    /** Generated by the database from the fields above; read-only here. */
    @Column(insertable = false, updatable = false)
    private String searchText;

    @ElementCollection(fetch = FetchType.LAZY)
    @CollectionTable(name = "candidate_skills", joinColumns = @JoinColumn(name = "candidate_id"))
    @BatchSize(size = 50)
    private Set<CandidateSkillEntry> skills = new HashSet<>();

    protected Candidate() {}

    public Candidate(String firstName, String lastName, String email, String phone, String currentTitle,
                     String currentCompany, String location, Integer yearsExperience, CandidateSource source,
                     String summary, String linkedinUrl, UUID ownerId, Instant retentionUntil) {
        this.firstName = firstName.trim();
        this.lastName = lastName.trim();
        this.email = normalizeEmail(email);
        this.phone = clean(phone);
        this.currentTitle = clean(currentTitle);
        this.currentCompany = clean(currentCompany);
        this.location = clean(location);
        this.yearsExperience = yearsExperience;
        this.source = source;
        this.summary = clean(summary);
        this.linkedinUrl = clean(linkedinUrl);
        this.ownerId = ownerId;
        this.retentionUntil = retentionUntil;
    }

    public static String normalizeEmail(String email) {
        return email.trim().toLowerCase(java.util.Locale.ROOT);
    }

    private static String clean(String value) {
        return value == null || value.isBlank() ? null : value.trim();
    }

    /** Applies a partial update and returns the names of the fields that actually changed (for the audit log). */
    public List<String> apply(CandidateChanges c) {
        List<String> changed = new ArrayList<>();
        if (c.firstName() != null && !c.firstName().trim().equals(firstName)) {
            firstName = c.firstName().trim();
            changed.add("firstName");
        }
        if (c.lastName() != null && !c.lastName().trim().equals(lastName)) {
            lastName = c.lastName().trim();
            changed.add("lastName");
        }
        if (c.email() != null && !normalizeEmail(c.email()).equals(email)) {
            email = normalizeEmail(c.email());
            changed.add("email");
        }
        if (c.phone() != null && !Objects.equals(clean(c.phone()), phone)) {
            phone = clean(c.phone());
            changed.add("phone");
        }
        if (c.currentTitle() != null && !Objects.equals(clean(c.currentTitle()), currentTitle)) {
            currentTitle = clean(c.currentTitle());
            changed.add("currentTitle");
        }
        if (c.currentCompany() != null && !Objects.equals(clean(c.currentCompany()), currentCompany)) {
            currentCompany = clean(c.currentCompany());
            changed.add("currentCompany");
        }
        if (c.location() != null && !Objects.equals(clean(c.location()), location)) {
            location = clean(c.location());
            changed.add("location");
        }
        if (c.yearsExperience() != null && !c.yearsExperience().equals(yearsExperience)) {
            yearsExperience = c.yearsExperience();
            changed.add("yearsExperience");
        }
        if (c.source() != null && c.source() != source) {
            source = c.source();
            changed.add("source");
        }
        if (c.summary() != null && !Objects.equals(clean(c.summary()), summary)) {
            summary = clean(c.summary());
            changed.add("summary");
        }
        if (c.linkedinUrl() != null && !Objects.equals(clean(c.linkedinUrl()), linkedinUrl)) {
            linkedinUrl = clean(c.linkedinUrl());
            changed.add("linkedinUrl");
        }
        return changed;
    }

    public void replaceSkills(Set<CandidateSkillEntry> newSkills) {
        skills.clear();
        skills.addAll(newSkills);
    }

    public void archive() {
        status = CandidateStatus.ARCHIVED;
    }

    public void restore() {
        status = CandidateStatus.ACTIVE;
    }

    public void setRetentionUntil(Instant retentionUntil) {
        this.retentionUntil = retentionUntil;
    }

    public boolean isArchived() {
        return status == CandidateStatus.ARCHIVED;
    }

    public String getFirstName() {
        return firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public String getEmail() {
        return email;
    }

    public String getPhone() {
        return phone;
    }

    public String getCurrentTitle() {
        return currentTitle;
    }

    public String getCurrentCompany() {
        return currentCompany;
    }

    public String getLocation() {
        return location;
    }

    public Integer getYearsExperience() {
        return yearsExperience;
    }

    public CandidateSource getSource() {
        return source;
    }

    public String getSummary() {
        return summary;
    }

    public String getLinkedinUrl() {
        return linkedinUrl;
    }

    public CandidateStatus getStatus() {
        return status;
    }

    public UUID getOwnerId() {
        return ownerId;
    }

    public Instant getRetentionUntil() {
        return retentionUntil;
    }

    public Set<CandidateSkillEntry> getSkills() {
        return Set.copyOf(skills);
    }
}
